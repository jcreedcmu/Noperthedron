#!/usr/bin/env python3
"""Generate Cayley/Checker/KGen.lean: fixed-size integer polynomial structures and
straight-line field-wise operations for the kernel checker.

Layouts (box variables t0..t4 in [-1,1]):
  X6  : (t0,t1) monomials 1, t0, t1, t0^2, t0 t1, t1^2
  S9  : (t2,t3) monomials t2^a t3^b, index a + 3 b (a, b <= 2)
  R3  : t4 monomials 1, t4, t4^2
  Y27 : (t2,t3,t4) monomials t2^a t3^b t4^c, index a + 3 b + 9 c
"""
import itertools, sys

def M(a, b): return f"(Int.mul {a} {b})"
def ADD(terms):
    terms = list(terms)
    if not terms: return "0"
    e = terms[0]
    for t in terms[1:]: e = f"(Int.add {e} {t})"
    return e

X6 = [(0,0),(1,0),(0,1),(2,0),(1,1),(0,2)]
def yexp(j): return (j%3, (j//3)%3, j//9)

out = []
w = out.append
w("module\n\n@[expose] public section\n")
w("/-! Generated by scripts/cayley/gen_kgap.py — do not edit. -/\n")
w("namespace Cayley.K\n")
w("set_option maxRecDepth 20000\n")

def struct(name, n, doc):
    w(f"/-- {doc} -/")
    w(f"structure {name} where")
    for i in range(n): w(f"  f{i} : Int")
    w("deriving Inhabited\n")
    fs = " ".join(f"f{i}" for i in range(n))
    w(f"def {name}.add (a b : {name}) : {name} := ⟨" + ", ".join(f"Int.add a.f{i} b.f{i}" for i in range(n)) + "⟩")
    w(f"def {name}.sub (a b : {name}) : {name} := ⟨" + ", ".join(f"Int.sub a.f{i} b.f{i}" for i in range(n)) + "⟩")
    w(f"def {name}.smul (c : Int) (a : {name}) : {name} := ⟨" + ", ".join(f"Int.mul c a.f{i}" for i in range(n)) + "⟩")
    w(f"def {name}.zero : {name} := ⟨" + ", ".join("0" for i in range(n)) + "⟩")
    w(f"/-- Sum of absolute values of all non-constant coefficients. -/")
    w(f"def {name}.slack (a : {name}) : Int := " + " + ".join(f"(a.f{i}).natAbs" for i in range(1, n)) )
    w("")

struct("X6", 6, "Polynomial in `t₀, t₁` of total degree ≤ 2.")
struct("S9", 9, "Polynomial in `t₂, t₃`, degree ≤ 2 in each.")
struct("R3", 3, "Polynomial in `t₄` of degree ≤ 2.")
struct("Y27", 27, "Polynomial in `t₂, t₃, t₄`, degree ≤ 2 in each.")

# X6 product of two linear forms (only slots 0,1,2 used)
def xmul():
    a = lambda i: f"a.f{i}"; b = lambda i: f"b.f{i}"
    terms = {0: M(a(0),b(0)), 1: ADD([M(a(0),b(1)), M(a(1),b(0))]), 2: ADD([M(a(0),b(2)), M(a(2),b(0))]),
             3: M(a(1),b(1)), 4: ADD([M(a(1),b(2)), M(a(2),b(1))]), 5: M(a(2),b(2))}
    w("/-- Product of two affine forms (slots 0–2). -/")
    w("def X6.mulLin (a b : X6) : X6 := ⟨" + ", ".join(terms[i] for i in range(6)) + "⟩\n")
xmul()

# S9 product of two affine forms in t2,t3 (slots 0 (1), 1 (t2), 3 (t3))
def smul_lin():
    w("/-- Product of two affine forms in `t₂, t₃` (slots 0, 1, 3). -/")
    t = {}
    lin = [(0,(0,0)),(1,(1,0)),(3,(0,1))]
    acc = {i: [] for i in range(9)}
    for (i,ei),(j,ej) in itertools.product(lin, lin):
        e = (ei[0]+ej[0], ei[1]+ej[1]); k = e[0] + 3*e[1]
        acc[k].append(M(f"a.f{i}", f"b.f{j}"))
    w("def S9.mulLin (a b : S9) : S9 := ⟨" + ", ".join(ADD(acc[k]) for k in range(9)) + "⟩\n")
smul_lin()

# Y27 = S9 ⊗ R3
w("/-- `s ⊗ r` as a polynomial in `t₂, t₃, t₄`. -/")
w("def S9.outerR (s : S9) (r : R3) : Y27 := ⟨" + ", ".join(M(f"s.f{j % 9}", f"r.f{j // 9}") for j in range(27)) + "⟩\n")

# Y27 product of two affine forms (slots 0, 1 (t2), 3 (t3), 9 (t4))
def ymul_lin():
    lin = [(0,(0,0,0)),(1,(1,0,0)),(3,(0,1,0)),(9,(0,0,1))]
    acc = {i: [] for i in range(27)}
    for (i,ei),(j,ej) in itertools.product(lin, lin):
        e = tuple(x+y for x,y in zip(ei,ej)); k = e[0]+3*e[1]+9*e[2]
        acc[k].append(M(f"a.f{i}", f"b.f{j}"))
    w("/-- Product of two affine forms in `t₂, t₃, t₄` (slots 0, 1, 3, 9). -/")
    w("def Y27.mulLin (a b : Y27) : Y27 := ⟨" + ", ".join(ADD(acc[k]) for k in range(27)) + "⟩\n")
ymul_lin()

# Bilinear X6 ⊗ Y27 data: we never store it; we generate functions for statistics.
# classes: for slot (i,j): exps
def cls(i, j):
    ex = X6[i]; ey = yexp(j)
    e = list(ex) + list(ey)
    deg = sum(e)
    if deg == 0: return "const"
    if deg == 1: return ("lin", e.index(1))
    if all(x % 2 == 0 for x in e): return "even"
    return "odd"

# A = Σ_k α_k ⊗ β_k : stats (c0, lin0..4, nl) where nl = Σ |nonlinear coefficients|
w("/-- Statistics of a polynomial: constant term, the five linear coefficients and the")
w("sum of absolute values of the other coefficients. -/")
w("structure Stats where\n  c0 : Int\n  l0 : Int\n  l1 : Int\n  l2 : Int\n  l3 : Int\n  l4 : Int\n  nl : Int\nderiving Inhabited\n")

def coef(i, j, xs, ys):
    return ADD(M(f"{x}.f{i}", f"{y}.f{j}") for x, y in zip(xs, ys))

def stats_fn(name, xs, ys, extra=None):
    """stats of Σ x_k ⊗ y_k (optionally minus u ⊗ v)."""
    args = " ".join(xs + ys)
    lines = []
    lin = {}
    c0 = None
    nl = []
    for i in range(6):
        for j in range(27):
            e = coef(i, j, xs, ys)
            if extra: e = f"(Int.sub {e} {M(extra[0]+'.f'+str(i), extra[1]+'.f'+str(j))})"
            c = cls(i, j)
            v = f"v{i}_{j}"
            lines.append(f"  let {v} := {e}")
            if c == "const": c0 = v
            elif isinstance(c, tuple): lin[c[1]] = v
            else: nl.append(f"{v}.natAbs")
    return lines, c0, lin, nl

def gen_stats():
    xs = ["a0", "a1", "a2"]; ys = ["b0", "b1", "b2"]
    lines, c0, lin, nl = stats_fn("A", xs, ys)
    w("/-- Statistics of `Σₖ aₖ ⊗ bₖ`. -/")
    w("def stats3 (a0 a1 a2 : X6) (b0 b1 b2 : Y27) : Stats :=")
    for l in lines: w(l)
    w(f"  ⟨{c0}, {lin[0]}, {lin[1]}, {lin[2]}, {lin[3]}, {lin[4]}, " + " + ".join(nl) + "⟩\n")
gen_stats()

def gen_full():
    # lower bound of Σ_k a_k ⊗ b_k − x ⊗ d : c0 + Σ_even min(0,·) − Σ_odd |·|
    xs = ["a0", "a1", "a2"]; ys = ["b0", "b1", "b2"]
    w("/-- Lower bound on `[-1,1]⁵` of `Σₖ aₖ ⊗ bₖ − x ⊗ d`. -/")
    w("def fullLower (a0 a1 a2 : X6) (b0 b1 b2 : Y27) (x : X6) (d : Y27) : Int :=")
    terms = []
    for i in range(6):
        for j in range(27):
            e = f"(Int.sub {coef(i, j, xs, ys)} {M('x.f'+str(i), 'd.f'+str(j))})"
            v = f"v{i}_{j}"
            w(f"  let {v} := {e}")
            c = cls(i, j)
            if c == "const": terms.append(v)
            elif c == "even": terms.append(f"min 0 {v}")
            else: terms.append(f"-({v}.natAbs : Int)")
    w("  " + " + ".join(terms) + "\n")
gen_full()

def gen_lower1():
    # lower bound of Σ_k a_k ⊗ b_k (used for the paired L test)
    xs = ["a0", "a1", "a2"]; ys = ["b0", "b1", "b2"]
    w("/-- Lower bound on `[-1,1]⁵` of `Σₖ aₖ ⊗ bₖ`. -/")
    w("def lower3 (a0 a1 a2 : X6) (b0 b1 b2 : Y27) : Int :=")
    terms = []
    for i in range(6):
        for j in range(27):
            v = f"v{i}_{j}"
            w(f"  let {v} := {coef(i, j, xs, ys)}")
            c = cls(i, j)
            if c == "const": terms.append(v)
            elif c == "even": terms.append(f"min 0 {v}")
            else: terms.append(f"-({v}.natAbs : Int)")
    w("  " + " + ".join(terms) + "\n")
gen_lower1()

# degree-4 (t0,t1) polynomials
X15 = [(a, d - a) for d in range(5) for a in range(d, -1, -1)]  # monomials t0^a t1^b, a+b<=4
X15IDX = {e: i for i, e in enumerate(X15)}
struct("X15", 15, "Polynomial in `t₀, t₁` of total degree ≤ 4.")
acc = {i: [] for i in range(15)}
for i, ei in enumerate(X6):
    for j, ej in enumerate(X6):
        acc[X15IDX[(ei[0]+ej[0], ei[1]+ej[1])]].append(M(f"a.f{i}", f"b.f{j}"))
w("/-- Product of two `X6` polynomials. -/")
w("def X6.mulX (a b : X6) : X15 := ⟨" + ", ".join(ADD(acc[k]) for k in range(15)) + "⟩\n")

def cls15(i, j):
    ex = X15[i]; ey = yexp(j)
    e = list(ex) + list(ey)
    if sum(e) == 0: return "const"
    if all(x % 2 == 0 for x in e): return "even"
    return "odd"

w("/-- A bilinear table `X15 ⊗ Y27`, by rows. -/")
w("structure T15 where")
for k in range(15): w(f"  r{k} : Y27")
w("deriving Inhabited\n")
hs = [f"h{k}" for k in range(6)]; ws = [f"w{k}" for k in range(6)]
w("/-- `Σₖ hₖ ⊗ wₖ` over six terms, by rows. -/")
def rowexpr(i):
    e = f"({ws[0]}.smul {hs[0]}.f{i})"
    for h, ww in list(zip(hs, ws))[1:]:
        e = f"(Y27.add {e} ({ww}.smul {h}.f{i}))"
    return e
w("def prod6H (" + " ".join(hs) + " : X15) (" + " ".join(ws) + " : Y27) : T15 := ⟨" +
  ", ".join(rowexpr(i) for i in range(15)) + "⟩\n")
w("/-- Lower bound on `[-1,1]⁵` of `T − x ⊗ y`. -/")
w("def lowerH (T : T15) (x : X15) (y : Y27) : Int :=")
terms = []
for i in range(15):
    w(f"  let q{i} := Y27.sub T.r{i} (y.smul x.f{i})")
    for j in range(27):
        c = cls15(i, j); v = f"q{i}.f{j}"
        if c == "const": terms.append(v)
        elif c == "even": terms.append(f"(min 0 {v})")
        else: terms.append(f"(Int.neg ({v}.natAbs : Int))")
w("  " + ADD(terms) + "\n")

# lower bound of a Y27 polynomial
w("/-- Lower bound on `[-1,1]³` of a `Y27` polynomial. -/")
terms = []
for j in range(27):
    e = yexp(j)
    if j == 0: terms.append("a.f0")
    elif all(x % 2 == 0 for x in e): terms.append(f"(min 0 a.f{j})")
    else: terms.append(f"(Int.neg (a.f{j}.natAbs : Int))")
w("def Y27.lower (a : Y27) : Int := " + ADD(terms) + "\n")

# stored bilinear table
w("/-- A bilinear table `X6 ⊗ Y27` (slot `27 i + j`). -/")
w("structure B162 where")
for k in range(162): w(f"  f{k} : Int")
w("deriving Inhabited\n")
xs = ["a0", "a1", "a2"]; ys = ["b0", "b1", "b2"]
w("/-- `Σₖ aₖ ⊗ bₖ`. -/")
w("def prod3 (a0 a1 a2 : X6) (b0 b1 b2 : Y27) : B162 := ⟨" + ", ".join(coef(i, j, xs, ys) for i in range(6) for j in range(27)) + "⟩\n")
w("/-- Statistics of a stored table. -/")
lin = {}; c0 = None; nl = []
for i in range(6):
    for j in range(27):
        c = cls(i, j); v = f"A.f{27*i+j}"
        if c == "const": c0 = v
        elif isinstance(c, tuple): lin[c[1]] = v
        else: nl.append(f"({v}).natAbs")
w(f"def statsB (A : B162) : Stats := ⟨{c0}, {lin[0]}, {lin[1]}, {lin[2]}, {lin[3]}, {lin[4]}, " + ADD(nl) + "⟩\n")
w("/-- Lower bound on `[-1,1]⁵` of `A − x ⊗ d`. -/")
w("def fullLowerB (A : B162) (x : X6) (d : Y27) : Int :=")
terms = []
for i in range(6):
    for j in range(27):
        v = f"v{i}_{j}"
        w(f"  let {v} := Int.sub A.f{27*i+j} {M('x.f'+str(i), 'd.f'+str(j))}")
        c = cls(i, j)
        if c == "const": terms.append(v)
        elif c == "even": terms.append(f"(min 0 {v})")
        else: terms.append(f"(Int.neg ({v}.natAbs : Int))")
w("  " + ADD(terms) + "\n")

w("end Cayley.K\n\nend")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
